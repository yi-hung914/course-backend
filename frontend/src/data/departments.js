export function eduSystemName(key) {
  return EDU_SYSTEMS.find(s => s.value === key)?.label || key;
}

// 下拉選單、標籤顯示用（找不到就退回 DEPT_MAP 或代碼）
export function deptLabel(code) {
  return DEPT_LABEL_MAP[code] || DEPT_MAP[code] || String(code);
}

// 某個系所代碼屬於哪些學制（例如護理系同時在二技和二技(三年)）
export function systemsOfDept(code) {
  return Object.keys(departmentData)
    .filter(key => (departmentData[key] || []).includes(code))
    .map(eduSystemName);
}

// 系所標籤附上學制，否則二技護理系和四技護理系都只顯示「護理系」
export function deptTagLabel(code) {
  const systems = systemsOfDept(code);
  return systems.length ? `${deptLabel(code)}（${systems.join("／")}）` : deptLabel(code);
}
